"""
static_eval.py — LLM-as-judge static code evaluation.

Evaluates the generated source code against the spec BEFORE execution.

Requires:
    pip install openai
Environment variables:
    OPENAI_API_KEY
"""

import json
from openai import OpenAI
from dotenv import load_dotenv
load_dotenv(override=True)

client = OpenAI()

# ---------------------------------------------------------------------------
# Prompt
# ---------------------------------------------------------------------------

PROMPT_TEMPLATE = """
You are evaluating Python source code generated by a code generation tool.
The code must implement an MCP-based agent using LangGraph that lists and filters
GitHub Issues or Pull Requests from a given repository.

Evaluate each criterion below and return ONLY a JSON object — no extra text.

---
SPEC:
{spec_text}

---
GENERATED CODE:
{source_code}

---
Return this exact JSON structure:

{{
  "scores": {{
    "correct_signature":       <0|1>,
    "correct_return_type":     <0|1>,
    "real_mcp_endpoint":       <0|1>,
    "dynamic_tool_loading":    <0|1>,
    "langgraph_orchestration": <0|1>,
    "llm_bound_to_tools":      <0|1>,
    "no_mocks_or_stubs":       <0|1>,
    "system_prompt_coverage":  <0|1>,
    "single_tool_per_run":     <0|1>,
    "failure_handling":        <0|1>,
    "build_graph_function":    <0|1>
  }},
  "total_score": <int>,
  "max_score": 11,
  "passed": <bool>,
  "summary": "<one paragraph describing the main issues found, or 'No issues found'>"
}}

Criteria definitions:
- correct_signature:       agent() has exactly (repository, user_request, github_token) as parameters
- correct_return_type:     agent() returns str | dict — a natural language string on success, a dict with at least (repository, status, message) on failure
- real_mcp_endpoint:       uses MultiServerMCPClient connecting to https://api.githubcopilot.com/mcp/
- dynamic_tool_loading:    calls get_tools() at runtime — no hardcoded tool list
- langgraph_orchestration: orchestration is implemented with LangGraph StateGraph
- llm_bound_to_tools:      LLM is bound to MCP tools via bind_tools() or equivalent
- no_mocks_or_stubs:       no hardcoded responses, fake data, or stubbed tools
- system_prompt_coverage:  system prompt instructs the LLM to state the action taken, repository, filtered results (number/title/state per item), outcome status, and a short message
- single_tool_per_run:     agent selects and invokes exactly one tool per execution (list_issues OR list_pull_requests), never both
- failure_handling:        catches TimeoutError and general exceptions; always returns without raising — failure dict must contain at least repository, status, and message
- build_graph_function:    code defines a build_graph(tools) function that receives tools and returns a compiled LangGraph graph

passed = true only if total_score == 11.
Be strict: partial implementations score 0.
"""


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def run_static_eval(
    source_code: str,
    spec_text: str,
    verbose: bool = True,
) -> dict:
    """
    Args:
        source_code: Full Python source code generated by the codegen tool.
        spec_text:   Full spec markdown used to generate the code.
        verbose:     Print results to stdout.

    Returns:
        {"passed": bool, "total_score": int, "max_score": int, "scores": dict, "summary": str}
    """
    prompt = PROMPT_TEMPLATE.format(spec_text=spec_text, source_code=source_code)

    response = client.chat.completions.create(
        model="gpt-4o",
        temperature=0,
        messages=[{"role": "user", "content": prompt}],
        response_format={"type": "json_object"},
    )

    result = json.loads(response.choices[0].message.content)

    if verbose:
        print(f"\n=== Static Code Evaluation ===")
        print(f"Score: {result['total_score']}/{result['max_score']} | Passed: {result['passed']}")
        for k, v in result.get("scores", {}).items():
            print(f"  {'✅' if v else '❌'} {k}")
        print(f"\nSummary: {result.get('summary', '')}")

    return result