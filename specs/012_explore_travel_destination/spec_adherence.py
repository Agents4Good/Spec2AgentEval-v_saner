import json
from openai import OpenAI
from dotenv import load_dotenv
load_dotenv(override=True)

client = OpenAI()


PROMPT_TEMPLATE = """
You are evaluating Python source code generated by a code generation tool.
The code must implement a travel destination assistant agent using LangGraph and GPT-4o,
capable of answering questions about weather, destination news, and general travel information.

Evaluate the criteria below and return ONLY a JSON object — no extra text.

---
SPEC:
{spec_text}

---
GENERATED CODE:
{source_code}

---
Return this exact JSON structure:

{{
  "scores": {{
    "correct_signature":       <0|1>,
    "correct_return_type":     <0|1>,
    "uses_langgraph_stategraph": <0|1>,
    "uses_chat_openai_gpt4o":  <0|1>,
    "build_graph_function":    <0|1>,
    "implements_get_weather":  <0|1>,
    "implements_search_news":  <0|1>,
    "weather_uses_wttrin":     <0|1>,
    "news_uses_tavily":        <0|1>,
    "llm_bound_to_tools":      <0|1>,
    "handles_empty_request":   <0|1>,
    "no_mocks_or_stubs":       <0|1>
  }},
  "total_score": <int>,
  "max_score": 12,
  "passed": <bool>,
  "summary": "<one paragraph with main issues found, or 'No issues found'>"
}}

Criteria definitions:
- correct_signature:         agent() has exactly (user_request: str) as parameter
- correct_return_type:       agent() returns a dict with exactly the keys: status, user_request, response
- uses_langgraph_stategraph: orchestration is implemented with LangGraph StateGraph
- uses_chat_openai_gpt4o:    uses ChatOpenAI with model="gpt-4o"
- build_graph_function:      defines a build_graph() function that returns a compiled LangGraph graph
- implements_get_weather:    defines a tool named get_weather that accepts a city parameter
- implements_search_news:    defines a tool named search_destination_news that accepts a query or destination parameter
- weather_uses_wttrin:       get_weather fetches data from https://wttr.in/<city_name>?format=j1 — no mock, no hardcoded data
- news_uses_tavily:          search_destination_news uses TavilyClient authenticated via TAVILY_API_KEY environment variable — no mock
- llm_bound_to_tools:        LLM is bound to tools via bind_tools() or equivalent so the LLM can select tools based on intent
- handles_empty_request:     agent() returns status "failure" when user_request is empty or blank
- no_mocks_or_stubs:         no hardcoded responses, fake data, or stubbed tool outputs anywhere in the code

passed = true only if total_score == 12.
Be strict: partial implementations score 0.
"""


def run_static_eval(
    source_code: str,
    spec_text: str,
    verbose: bool = True,
) -> dict:
    """
    Args:
        source_code: Full Python source code generated by the codegen tool.
        spec_text:   Full spec markdown used to generate the code.
        verbose:     Print results to stdout.

    Returns:
        {"passed": bool, "total_score": int, "max_score": int, "scores": dict, "summary": str}
    """
    prompt = PROMPT_TEMPLATE.format(spec_text=spec_text, source_code=source_code)

    response = client.chat.completions.create(
        model="gpt-4o",
        temperature=0,
        messages=[{"role": "user", "content": prompt}],
        response_format={"type": "json_object"},
    )

    result = json.loads(response.choices[0].message.content)

    if verbose:
        print(f"\n=== Static Code Evaluation ===")
        print(f"Score: {result['total_score']}/{result['max_score']} | Passed: {result['passed']}")
        for k, v in result.get("scores", {}).items():
            print(f"  {'✅' if v else '❌'} {k}")
        print(f"\nSummary: {result.get('summary', '')}")

    return result