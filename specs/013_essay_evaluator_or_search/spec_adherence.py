import json
from openai import OpenAI
from dotenv import load_dotenv
load_dotenv(override=True)

client = OpenAI()


PROMPT_TEMPLATE = """
You are evaluating Python source code generated by a code generation tool.

The code must implement an Essay Assistant Agent using LangGraph and GPT-4o,
capable of selecting between two tools (fetch_document or search_about_topic)
or answering directly based on user intent.

Evaluate the criteria below and return ONLY a JSON object — no extra text.

---
SPEC:
{spec_text}

---
GENERATED CODE:
{source_code}

---
Return this exact JSON structure:

{{
  "scores": {{
    "correct_signature":           <0|1>,
    "correct_return_type":         <0|1>,
    "uses_langgraph_stategraph":   <0|1>,
    "uses_chat_openai_gpt4o":      <0|1>,
    "build_graph_function":        <0|1>,
    "implements_fetch_document":   <0|1>,
    "implements_search_about_topic": <0|1>,
    "fetch_document_uses_http":    <0|1>,
    "search_uses_tavily":          <0|1>,
    "llm_selects_tools":           <0|1>,
    "max_one_tool_per_execution":  <0|1>,
    "handles_empty_request":       <0|1>,
    "no_mocks_or_stubs":           <0|1>
  }},
  "total_score": <int>,
  "max_score": 13,
  "passed": <bool>,
  "summary": "<one paragraph with main issues found, or 'No issues found'>"
}}

Criteria definitions:

- correct_signature: agent() has exactly (user_request: str) as parameter
- correct_return_type: agent() returns a dict with exactly the keys: status, user_request, response
- uses_langgraph_stategraph: orchestration is implemented using LangGraph StateGraph
- uses_chat_openai_gpt4o: uses ChatOpenAI with model="gpt-4o"
- build_graph_function: defines a build_graph() function that returns a compiled LangGraph graph
- implements_fetch_document: defines a tool named fetch_document that receives a URL
- implements_search_about_topic: defines a tool named search_about_topic that receives a query/topic
- fetch_document_uses_http_requests: fetch_document performs a real HTTP GET request (e.g., requests.get) and returns actual content
- search_uses_tavily: search_about_topic uses TavilyClient authenticated via TAVILY_API_KEY — no mocks
- llm_selects_tools: the LLM is responsible for deciding whether to call a tool (e.g., via bind_tools or explicit intent routing)
- max_one_tool_per_execution: the graph structure guarantees that at most one tool is invoked per execution (no loops back to tool node)
- handles_empty_request: agent() returns status "failure" when user_request is empty or blank
- no_mocks_or_stubs: no hardcoded responses, fake data, or stubbed tool outputs anywhere in the code

Rules:
- Be strict: partial implementations score 0.
- If a criterion is ambiguous or weakly satisfied, score 0.
- passed = true ONLY if total_score == max_score.
"""


def run_static_eval(
    source_code: str,
    spec_text: str,
    verbose: bool = True,
) -> dict:
    """
    Args:
        source_code: Full Python source code generated by the codegen tool.
        spec_text:   Full spec markdown used to generate the code.
        verbose:     Print results to stdout.

    Returns:
        {"passed": bool, "total_score": int, "max_score": int, "scores": dict, "summary": str}
    """
    prompt = PROMPT_TEMPLATE.format(spec_text=spec_text, source_code=source_code)

    response = client.chat.completions.create(
        model="gpt-4o",
        temperature=0,
        messages=[{"role": "user", "content": prompt}],
        response_format={"type": "json_object"},
    )

    result = json.loads(response.choices[0].message.content)

    if verbose:
        print(f"\n=== Static Code Evaluation ===")
        print(f"Score: {result['total_score']}/{result['max_score']} | Passed: {result['passed']}")
        for k, v in result.get("scores", {}).items():
            print(f"  {'✅' if v else '❌'} {k}")
        print(f"\nSummary: {result.get('summary', '')}")

    return result
