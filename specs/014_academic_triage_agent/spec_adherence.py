import json
from openai import OpenAI
from dotenv import load_dotenv
load_dotenv(override=True)

client = OpenAI()


PROMPT_TEMPLATE = """
You are an expert code reviewer and compliance judge.
Your task is to evaluate a Python source code implementation of an AI Agent against its official Specification.

The code must implement a "Basic Assistant Agent" using LangGraph and OpenAI.

Evaluate the code strictly against the criteria below.
CRITICAL: Return ONLY a valid, raw JSON object. Do not include introductory text, explanations, or markdown code blocks (e.g., do not use ```json ... ```).

---
SPECIFICATION:
{spec_text}

---
GENERATED CODE:
{source_code}

---
Return this exact JSON structure:
{{
  "scores": {{
    "correct_return_type":          <0|1>,
    "uses_langgraph_stategraph":    <0|1>,
    "uses_messages_state":          <0|1>,
    "uses_chat_openai_gpt4o":       <0|1>,
    "build_graph_function":         <0|1>,
    "extracts_last_message":        <0|1>,
    "handles_error_schema":         <0|1>
  }},
  "total_score": <int>,
  "max_score": 7,
  "passed": <bool>,
  "summary": "<One concise paragraph explaining the main issues found. If total_score is 10, return 'No issues found.'>"
}}

---
CRITERIA DEFINITIONS (Score 1 if True, 0 if False):
- correct_return_type:          The main function includes the return type hint `-> str` OR strictly returns a string object.
- uses_langgraph_stategraph:    The code imports and uses `StateGraph` from LangGraph for orchestration.
- uses_messages_state:          The code imports and uses LangGraph's prebuilt `MessagesState` to manage the graph's state.
- uses_chat_openai_gpt4o:       The LLM is instantiated exactly as `ChatOpenAI(model="gpt-4o"...)` (or similar valid kwargs).
- build_graph_function:         There is a `def build_graph()` function that compiles and returns a LangGraph object (e.g., `return graph.compile()`).
- extracts_last_message:        The code correctly extracts the string content of the last message from the LangGraph execution output state.
- handles_error_schema:         The code has a fallback mechanism (e.g., try/except or if/else) that returns EXACTLY the literal string: "Error: Unable to get response from agent."

RULES:
- `passed` must be `true` ONLY if `total_score` == 7.
- Be extremely strict: partial or "almost correct" implementations score 0 for that specific criterion.
"""


def run_static_eval(
    source_code: str,
    spec_text: str,
    verbose: bool = True,
) -> dict:
    """
    Args:
        source_code: Full Python source code generated by the codegen tool.
        spec_text:   Full spec markdown used to generate the code.
        verbose:     Print results to stdout.

    Returns:
        {"passed": bool, "total_score": int, "max_score": int, "scores": dict, "summary": str}
    """
    prompt = PROMPT_TEMPLATE.format(spec_text=spec_text, source_code=source_code)

    response = client.chat.completions.create(
        model="gpt-4o",
        temperature=0,
        messages=[{"role": "user", "content": prompt}],
        response_format={"type": "json_object"},
    )

    result = json.loads(response.choices[0].message.content)

    if verbose:
        print(f"\n=== Static Code Evaluation ===")
        print(f"Score: {result['total_score']}/{result['max_score']} | Passed: {result['passed']}")
        for k, v in result.get("scores", {}).items():
            print(f"  {'✅' if v else '❌'} {k}")
        print(f"\nSummary: {result.get('summary', '')}")

    return result
