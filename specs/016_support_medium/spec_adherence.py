"""
static_eval.py — LLM-as-judge static code evaluation.


Evaluates the generated source code against the spec BEFORE execution.


Requires:
   pip install openai
Environment variables:
   OPENAI_API_KEY
"""


import json
from openai import OpenAI
from dotenv import load_dotenv
load_dotenv(override=True)

client = OpenAI()

# ---------------------------------------------------------------------------
# Prompt
# ---------------------------------------------------------------------------


PROMPT_TEMPLATE = """
You are evaluating Python source code generated by a code generation tool.
The code must implement a customer support agent using LangGraph, according to the provided specification.


Your task is to evaluate whether the generated code correctly follows the specification BEFORE execution.
Evaluate the criteria below and return ONLY a JSON object — no extra text.


---
SPEC:
{spec_text}


---
GENERATED CODE:
{source_code}


---
Return this exact JSON structure:

{{
"scores": {{
    "correct_signature": <0|1>,
    "correct_return_type": <0|1>,
    "uses_langgraph": <0|1>,
    "uses_chat_openai_gpt4o": <0|1>,
    "classification_and_relevance": <0|1>,
    "implements_handle_support": <0|1>,
    "implements_escalate": <0|1>,
    "correct_sentiment_routing": <0|1>,
    "preserves_tool_arguments": <0|1>,
    "handles_invalid_input": <0|1>,
    "handles_analysis_failure": <0|1>,
    "handles_tool_failure": <0|1>,
    "correct_response_format": <0|1>
}},
"total_score": <int>,
"max_score": 13,
"passed": <bool>,
"summary": "<one paragraph describing the main implementation problems found in the code, or 'No problems found'>"
}}


Criteria definitions:
- correct_signature: Exposes agent(query) with query as its only caller-supplied input. Do not require type annotations that the specification does not require.
- correct_return_type: Every success and handled error returns a state dictionary with a required response field containing a string. Additional state fields are allowed.
- uses_langgraph: Uses LangGraph to implement the specified behavioral graph, including its routing, success paths, and error paths. An unused import is insufficient. Equivalent preflight validation or exception handling outside graph nodes is allowed. Do not require particular node names or a build_graph helper.
- uses_chat_openai_gpt4o: Uses ChatOpenAI configured with the GPT-4o model for the analytical LLM call. Accept equivalent model/model_name arguments and configuration whose effective value is demonstrably gpt-4o.
- classification_and_relevance: For each non-empty, non-whitespace string, performs exactly one analytical LLM call to assess customer-support relevance and, when relevant, identify one Category (Technical, Billing, General) and one Sentiment (Positive, Neutral, Negative) in that same call. The analysis follows the meanings defined in the spec. Classification must not be mocked or hardcoded. The separate response-generation call allowed inside handle_support is not a second analytical call.
- implements_handle_support: Implements handle_support(query, category) to generate a non-empty customer-facing support response addressing the query within that category. A mock, stub, or canned response that does not perform this task is insufficient. The tool may use at most one additional LLM call and must not repeat Category or Sentiment analysis.
- implements_escalate: Implements escalate(query) to forward the query to human support and return a non-empty confirmation only on confirmed success. An unconditional success string without a handoff is insufficient. Do not require a particular external service, transport, or library: the spec does not prescribe the runtime handoff integration.
- correct_sentiment_routing: After valid support analysis, calls exactly one tool once: escalate for Negative sentiment regardless of Category, or handle_support for Positive or Neutral sentiment. The unselected tool must not run.
- preserves_tool_arguments: Passes the original, unchanged query to the selected tool. For handle_support, also passes the exact Category produced by the analysis. Does not replace, normalize, or reclassify these arguments.
- handles_invalid_input: For None, non-string inputs, empty strings, and whitespace-only strings, returns response exactly 'Error: could not classify the query' before any LLM or tool call. For text identified as unrelated to customer support by the single analytical call, returns the same error without calling either tool.
- handles_analysis_failure: If the analytical call fails, relevance is undetermined, or a relevant query lacks exactly one allowed Category and Sentiment, returns response exactly 'Error: could not classify the query'. Rejects unusable analysis rather than substituting default values. Does not retry analysis or call either tool after failure, including missing or invalid LLM configuration handled at this stage.
- handles_tool_failure: If the selected tool raises or returns a non-string, empty, or whitespace-only value, returns response exactly 'Error: could not execute handle_support' or 'Error: could not execute escalate', according to the failed tool. Does not retry, call the other tool as fallback, or format a successful result. Includes response-generation LLM failures inside handle_support.
- correct_response_format: Only after the selected tool succeeds, sets response to exactly 'Category: {{category}}\\nSentiment: {{sentiment}}\\nResponse: {{tool_result}}', where \\n denotes a newline, Category and Sentiment retain the values from analysis, and tool_result is the unchanged string returned by the selected tool. On error, response contains only the specified error message, without a formatted classification or successful response.

passed = true only if total_score == max_score.
Be strict: partial implementations score 0.
"""

# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


def run_static_eval(
   source_code: str,
   spec_text: str,
   verbose: bool = True,
) -> dict:
   """
   Args:
       source_code: Full Python source code generated by the codegen tool.
       spec_text:   Full spec markdown used to generate the code.
       verbose:     Print results to stdout.


   Returns:
       {"passed": bool, "total_score": int, "max_score": int, "scores": dict, "summary": str}
   """
   prompt = PROMPT_TEMPLATE.format(spec_text=spec_text, source_code=source_code)


   response = client.chat.completions.create(
       model="gpt-4o",
       temperature=0,
       messages=[{"role": "user", "content": prompt}],
       response_format={"type": "json_object"},
   )


   result = json.loads(response.choices[0].message.content)


   if verbose:
       print(f"\n=== Static Code Evaluation ===")
       print(f"Score: {result['total_score']}/{result['max_score']} | Passed: {result['passed']}")
       for k, v in result.get("scores", {}).items():
           print(f"  {'✅' if v else '❌'} {k}")
       print(f"\nSummary: {result.get('summary', '')}")


   return result
