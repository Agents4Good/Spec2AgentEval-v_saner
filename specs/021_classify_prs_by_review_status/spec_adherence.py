"""
static_eval.py — LLM-as-judge static code evaluation.

Evaluates the generated source code against the spec BEFORE execution.

Requires:
    pip install openai
Environment variables:
    OPENAI_API_KEY
"""

import json
from openai import OpenAI
from dotenv import load_dotenv
load_dotenv(override=True)

client = OpenAI()

# ---------------------------------------------------------------------------
# Prompt
# ---------------------------------------------------------------------------

PROMPT_TEMPLATE = """
You are evaluating Python source code generated by a code generation tool.

The code must implement an MCP-based agent using LangGraph that analyzes
GitHub Pull Requests and classifies them based on review status.

The agent must:
- Retrieve open pull requests from a repository
- Select up to 3 most recently updated PRs
- Inspect their reviews using MCP tools
- Classify each PR as:
    * needs_review
    * reviewed

Evaluate each criterion below and return ONLY a JSON object — no extra text.

---
SPEC:
{spec_text}

---
GENERATED CODE:
{source_code}

---
Return this exact JSON structure:

{{
  "scores": {{
    "correct_signature":          <0|1>,
    "correct_return_type":        <0|1>,
    "real_mcp_endpoint":          <0|1>,
    "dynamic_tool_loading":       <0|1>,
    "langgraph_orchestration":    <0|1>,
    "llm_bound_to_tools":         <0|1>,
    "no_mocks_or_stubs":          <0|1>,
    "system_prompt_coverage":     <0|1>,
    "multi_step_tool_usage":      <0|1>,
    "classification_logic":       <0|1>,
    "subset_limitation":          <0|1>,
    "failure_handling":           <0|1>,
    "build_graph_function":       <0|1>
  }},
  "total_score": <int>,
  "max_score": 13,
  "passed": <bool>,
  "summary": "<one paragraph describing the main issues found, or 'No issues found'>"
}}

Criteria definitions:

- correct_signature: agent() has exactly (repository, user_request, github_token)

- correct_return_type: returns str | dict — string for success, dict with (repository, status, message) on failure

- real_mcp_endpoint: uses MultiServerMCPClient with https://api.githubcopilot.com/mcp/

- dynamic_tool_loading: calls get_tools() at runtime

- langgraph_orchestration: uses LangGraph StateGraph

- llm_bound_to_tools: LLM is bound to tools via bind_tools()

- no_mocks_or_stubs: no fake responses or hardcoded data

- system_prompt_coverage:
  system prompt clearly instructs the model to:
    * classify PRs into needs_review vs reviewed
    * include repository name
    * include PR number and title
    * include status (success/failure)
    * include summary message
    * include note about subset (max 3 PRs)

- multi_step_tool_usage:
  correctly performs multi-step tool usage:
    * first list pull requests
    * then fetch reviews for selected PRs

- classification_logic:
  implements correct classification:
    * needs_review = no reviews OR no final decision
    * reviewed = at least one approval or change request

- subset_limitation: limits analysis to at most 3 PRs (e.g., via perPage=3 or equivalent logic)

- failure_handling: catches TimeoutError and generic exceptions and returns structured failure response

- build_graph_function: defines build_graph(tools) returning compiled graph

passed = true only if total_score == max_score.
Be strict: partial implementations score 0.
"""


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def run_static_eval(
    source_code: str,
    spec_text: str,
    verbose: bool = True,
) -> dict:
    """
    Args:
        source_code: Full Python source code generated by the codegen tool.
        spec_text:   Full spec markdown used to generate the code.
        verbose:     Print results to stdout.

    Returns:
        {"passed": bool, "total_score": int, "max_score": int, "scores": dict, "summary": str}
    """
    prompt = PROMPT_TEMPLATE.format(spec_text=spec_text, source_code=source_code)

    response = client.chat.completions.create(
        model="gpt-4o",
        temperature=0,
        messages=[{"role": "user", "content": prompt}],
        response_format={"type": "json_object"},
    )

    result = json.loads(response.choices[0].message.content)

    if verbose:
        print(f"\n=== Static Code Evaluation ===")
        print(f"Score: {result['total_score']}/{result['max_score']} | Passed: {result['passed']}")
        for k, v in result.get("scores", {}).items():
            print(f"  {'✅' if v else '❌'} {k}")
        print(f"\nSummary: {result.get('summary', '')}")

    return result