"""
static_eval.py — LLM-as-judge static code evaluation.

Evaluates the generated source code against the spec BEFORE execution.

Requires:
    pip install openai
Environment variables:
    OPENAI_API_KEY
"""

import json
from openai import OpenAI
from dotenv import load_dotenv
load_dotenv(override=True)

client = OpenAI()

# ---------------------------------------------------------------------------
# Prompt
# ---------------------------------------------------------------------------

PROMPT_TEMPLATE = """
You are evaluating Python source code generated by a code generation tool.

The code must implement a travel destination assistant using GPT-4o,
ChatOpenAI, and LangGraph. It assesses destination viability by combining
real-time weather data from wttr.in and recent news from the Tavily Search API.

Evaluate each criterion below and return ONLY a JSON object — no extra text.

---
SPEC:
{spec_text}

---
GENERATED CODE:
{source_code}

---
Return this exact JSON structure:

{{
  "scores": {{
    "correct_signature":          <0|1>,
    "correct_return_schema":      <0|1>,
    "required_model_framework":   <0|1>,
    "langchain_tool_interfaces":  <0|1>,
    "weather_tool":               <0|1>,
    "news_tool":                  <0|1>,
    "destination_identification": <0|1>,
    "weather_retrieval":          <0|1>,
    "news_retrieval":             <0|1>,
    "combined_assessment":        <0|1>,
    "no_fabrication":             <0|1>,
    "empty_request_handling":     <0|1>,
    "failure_handling":           <0|1>,
    "global_timeout":             <0|1>,
    "langgraph_orchestration":    <0|1>,
    "behavioral_coverage":        <0|1>
  }},
  "total_score": <int>,
  "max_score": 16,
  "passed": <bool>,
  "summary": "<one paragraph describing the main issues found, or 'No issues found'>"
}}

Criteria definitions:

- correct_signature: entrypoint is agent(user_request: str) -> dict
- correct_return_schema: every return has exactly status and response; status is success/failure and response is a string
- required_model_framework: uses ChatOpenAI with GPT-4o and LangGraph
- langchain_tool_interfaces: get_weather and search_destination_news are LangChain tools and are called only through invoke/ainvoke or equivalent tool interfaces
- weather_tool: makes a real request to https://wttr.in/{city}?format=j1, parses weather data, and handles request/invalid-data errors
- news_tool: calls Tavily Search API using TAVILY_API_KEY and handles missing key, request errors, and timeouts
- destination_identification: identifies a city-level destination from the request when possible; does not invent one
- weather_retrieval: retrieves and uses real weather data for the identified destination
- news_retrieval: searches for recent news, events, or safety advisories and uses the results
- combined_assessment: assesses travel viability using both weather and news results
- no_fabrication: does not fabricate weather, news, safety claims, or sources; distinguishes missing evidence from confirmed facts
- empty_request_handling: empty/whitespace requests return failure without model or tool calls
- failure_handling: tool errors and exceptions return the required failure schema without propagating exceptions
- global_timeout: enforces a 30-second maximum for the entire agent execution, not only individual requests
- langgraph_orchestration: StateGraph actually orchestrates the behaviors and routes failures to failure handling
- behavioral_coverage: covers B1 identify destination, B2 retrieve weather, B3 search news, B4 assess viability, B5 empty request, B6 errors/timeouts, and B7 structured response

Award 1 only when the criterion is fully implemented; partial implementations score 0.
No mocks, stubs, hardcoded results, or unused imports/functions count as implementation.
The total_score must equal the sum of scores.
passed = true only if total_score == max_score.
"""


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def run_static_eval(
    source_code: str,
    spec_text: str,
    verbose: bool = True,
) -> dict:
    """
    Args:
        source_code: Full Python source code generated by the codegen tool.
        spec_text:   Full spec markdown used to generate the code.
        verbose:     Print results to stdout.

    Returns:
        {"passed": bool, "total_score": int, "max_score": int, "scores": dict, "summary": str}
    """
    prompt = PROMPT_TEMPLATE.format(spec_text=spec_text, source_code=source_code)

    response = client.chat.completions.create(
        model="gpt-4o",
        temperature=0,
        messages=[{"role": "user", "content": prompt}],
        response_format={"type": "json_object"},
    )

    result = json.loads(response.choices[0].message.content)

    if verbose:
        print(f"\n=== Static Code Evaluation ===")
        print(f"Score: {result['total_score']}/{result['max_score']} | Passed: {result['passed']}")
        for k, v in result.get("scores", {}).items():
            print(f"  {'✅' if v else '❌'} {k}")
        print(f"\nSummary: {result.get('summary', '')}")

    return result