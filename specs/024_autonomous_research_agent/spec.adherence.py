"""
static_eval.py — LLM-as-judge static code evaluation.

Evaluates the generated source code against the spec BEFORE execution.

Requires:
    pip install openai
Environment variables:
    OPENAI_API_KEY
"""

import json
from openai import OpenAI
from dotenv import load_dotenv
load_dotenv(override=True)

client = OpenAI()

# ---------------------------------------------------------------------------
# Prompt
# ---------------------------------------------------------------------------

PROMPT_TEMPLATE = """
You are evaluating Python source code generated by a code generation tool.
The code must implement an Email Assistant AI agent using LangGraph and the Notion API, according to the provided specification.

The code must implement an "Autonomous Research Agent" using LangGraph, OpenAI, and strict JSON outputs.
Evaluate the criteria below and return ONLY a JSON object — no extra text.

---
SPEC:
{spec_text}

---
GENERATED CODE:
{source_code}

---
Return this exact JSON structure:

{{
  "scores": {{
    "correct_signature":            <0|1>,
    "uses_langgraph_stategraph":    <0|1>,
    "uses_chat_openai_gpt4o":       <0|1>,
    "binds_and_uses_tools":         <0|1>,
    "defines_required_tools":       <0|1>,
    "build_graph_function":         <0|1>,
    "system_prompt_instructs_json": <0|1>,
    "fallback_logic_instructed":    <0|1>,
    "extracts_last_message":        <0|1>,
    "handles_strict_error_schema":  <0|1>
  }},
  "total_score": <int>,
  "max_score": 10,
  "passed": <bool>,
  "summary": "<One concise paragraph explaining the main issues found. If total_score is 10, return 'No issues found.'>"
}}

CRITERIA DEFINITIONS (Score 1 if True, 0 if False):
- correct_signature:            The main function is strictly defined as `def agent(user_request: str)` and explicitly or implicitly returns a string.
- uses_langgraph_stategraph:    The code imports and uses `StateGraph` from LangGraph and manages state with `MessagesState` (or a valid TypedDict with an annotated messages list).
- uses_chat_openai_gpt4o:       The LLM is instantiated exactly as `ChatOpenAI(model="gpt-4o"...)` (or similar valid kwargs).
- binds_and_uses_tools:         The code uses `.bind_tools()` to attach tools to the LLM and uses LangGraph's prebuilt `ToolNode` (or `tools_condition`) for routing.
- defines_required_tools:       The code defines exactly the three required tools (`search_arxiv`, `search_pubmed`, `get_wikipedia_summary`) using the LangChain `@tool` decorator.
- build_graph_function:         There is a `def build_graph(...)` function that compiles and returns a LangGraph object (e.g., `return graph.compile()`).
- system_prompt_instructs_json: The system prompt explicitly instructs the LLM to output its final response strictly as a valid JSON object without conversational filler text.
- fallback_logic_instructed:    The system prompt or the `get_wikipedia_summary` docstring explicitly instructs the agent to use its "internal knowledge" or "infer" the entity if Wikipedia fails/errors, rather than aborting.
- extracts_last_message:        The code correctly extracts the string content of the last message from the LangGraph execution output state to return it.
- handles_strict_error_schema:  The code has a fallback mechanism (e.g., try/except blocks) that catches timeouts or exceptions and returns EXACTLY the literal JSON string: `{{"status": "error", "message": "Execution failed or invalid request."}}`

passed = true only if total_score == max_score.
Be strict: partial implementations score 0.
"""


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def run_static_eval(
    source_code: str,
    spec_text: str,
    verbose: bool = True,
) -> dict:
    """
    Args:
        source_code: Full Python source code generated by the codegen tool.
        spec_text:   Full spec markdown used to generate the code.
        verbose:     Print results to stdout.

    Returns:
        {"passed": bool, "total_score": int, "max_score": int, "scores": dict, "summary": str}
    """
    prompt = PROMPT_TEMPLATE.format(spec_text=spec_text, source_code=source_code)

    response = client.chat.completions.create(
        model="gpt-4o",
        temperature=0,
        messages=[{"role": "user", "content": prompt}],
        response_format={"type": "json_object"},
    )

    result = json.loads(response.choices[0].message.content)

    if verbose:
        print(f"\n=== Static Code Evaluation ===")
        print(f"Score: {result['total_score']}/{result['max_score']} | Passed: {result['passed']}")
        for k, v in result.get("scores", {}).items():
            print(f"  {'✅' if v else '❌'} {k}")
        print(f"\nSummary: {result.get('summary', '')}")

    return result