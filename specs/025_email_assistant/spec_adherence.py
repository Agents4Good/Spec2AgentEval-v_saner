"""
static_eval.py — LLM-as-judge static code evaluation.

Evaluates the generated source code against the spec BEFORE execution.

Requires:
    pip install openai
Environment variables:
    OPENAI_API_KEY
"""

import json
from openai import OpenAI
from dotenv import load_dotenv
load_dotenv(override=True)

client = OpenAI()

# ---------------------------------------------------------------------------
# Prompt
# ---------------------------------------------------------------------------

PROMPT_TEMPLATE = """
You are evaluating Python source code generated by a code generation tool.
The code must implement an Email Assistant AI agent using LangGraph and the Notion API, according to the provided specification.

Your task is to evaluate whether the generated code correctly follows the specification BEFORE execution.
Evaluate the criteria below and return ONLY a JSON object — no extra text.

---
SPEC:
{spec_text}

---
GENERATED CODE:
{source_code}

---
Return this exact JSON structure:

{{
  "scores": {{
    "correct_signature":           <0|1>,
    "correct_return_type":         <0|1>,
    "langgraph_orchestration":     <0|1>,
    "llm_usage_for_reasoning":     <0|1>,
    "build_graph_function":        <0|1>,
    "notion_client_integration":   <0|1>,
    "calendar_tool_present":       <0|1>,
    "drafts_tool_present":         <0|1>,
    "handles_timeout_or_error":    <0|1>,
    "output_schema_present":       <0|1>
  }},
  "total_score": <int>,
  "max_score": 10,
  "passed": <bool>,
  "summary": "<one paragraph with main issues found, or 'No issues found'>"
}}

Criteria definitions:
- correct_signature:           agent() has exactly (email_input: str) as parameter.
- correct_return_type:         returns a Tuple[Any, dict] (or at least returns a tuple with a dict as the second element).
- langgraph_orchestration:     uses LangGraph (StateGraph) for orchestration and state management.
- llm_usage_for_reasoning:     LLM is used inside the graph nodes to classify the email and generate a response.
- build_graph_function:        code defines a function (or logic blocks) that compiles the nodes and tools into a graph.
- notion_client_integration:   uses the official `notion_client` SDK (Client) to connect to the Notion API via environment variables.
- calendar_tool_present:       implements a tool (e.g., check_calendar_availability) that queries a Notion data source/database for events.
- drafts_tool_present:         implements a tool (e.g., save_email_draft) that creates a new page in a Notion data source/database for drafts.
- handles_timeout_or_error:    contains a try-except block (or timeout handling) that returns status="failure" and classification="unknown" if an error/timeout occurs.
- output_schema_present:       output dict contains exactly action, classification, actions_taken, status, message, draft_response.

passed = true only if total_score == max_score.
Be strict: partial implementations score 0.
"""


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def run_static_eval(
    source_code: str,
    spec_text: str,
    verbose: bool = True,
) -> dict:
    """
    Args:
        source_code: Full Python source code generated by the codegen tool.
        spec_text:   Full spec markdown used to generate the code.
        verbose:     Print results to stdout.

    Returns:
        {"passed": bool, "total_score": int, "max_score": int, "scores": dict, "summary": str}
    """
    prompt = PROMPT_TEMPLATE.format(spec_text=spec_text, source_code=source_code)

    response = client.chat.completions.create(
        model="gpt-4o",
        temperature=0,
        messages=[{"role": "user", "content": prompt}],
        response_format={"type": "json_object"},
    )

    result = json.loads(response.choices[0].message.content)

    if verbose:
        print(f"\n=== Static Code Evaluation ===")
        print(f"Score: {result['total_score']}/{result['max_score']} | Passed: {result['passed']}")
        for k, v in result.get("scores", {}).items():
            print(f"  {'✅' if v else '❌'} {k}")
        print(f"\nSummary: {result.get('summary', '')}")

    return result