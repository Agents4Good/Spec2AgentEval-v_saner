from langchain_openai import ChatOpenAI
from dotenv import load_dotenv
load_dotenv(override=True)

llm = ChatOpenAI(model="gpt-4o")


PROMPT_TEMPLATE = """
You are evaluating Python source code generated by a code generation tool.
The code must implement a Personal Trainer agent using LangGraph and gpt-4o.

Evaluate the criteria below and return ONLY a JSON object — no extra text.

---
SPEC:
{spec_text}

---
GENERATED CODE:
{source_code}

---
Return this exact JSON structure:

{{
  "scores": {{
    "correct_signature":              <0|1>,
    "correct_return_type":            <0|1>,
    "correct_tools":           <0|1>,
    "native_tool_calling":            <0|1>,
    "enforces_sequential_tools":      <0|1>,
    "correct_model":                  <0|1>,
    "langgraph_orchestration":        <0|1>,
    "rejects_empty_profile":          <0|1>,
    "rejects_insufficient_profile":   <0|1>,
    "handles_execution_failure":      <0|1>,
    "generates_weekly_plan":          <0|1>,
    "handles_constraints":            <0|1>,
    "includes_intensity_progression": <0|1>,
    "includes_nutrition_guidance":    <0|1>,
    "includes_recovery_protocol":     <0|1>,
    "output_schema_enforced":         <0|1>,
    "no_hardcoded_plan":              <0|1>
  }},
  "total_score": <int>,
  "max_score": 17,
  "passed": <bool>,
  "summary": "<one paragraph with main issues found, or 'No issues found'>"
}}

Criteria definitions:
- correct_signature:              agent() has exactly (user_profile: str) as parameter.
- correct_return_type:            agent() returns a str.
- correct_tools:           contains exactly two tools: "retrieve_restrictions" and "search_exercises", with correct parameters.
- native_tool_calling:            the LLM is bound to tools using .bind_tools() and the routing uses LangGraph's tools_condition (or equivalent).
- enforces_sequential_tools:      the system prompt or logic explicitly enforces calling the Notion tool (retrieve_restrictions) FIRST, and waiting for its 
result before calling the tool search_exercises.
- correct_model:                  uses ChatOpenAI with model="gpt-4o".
- langgraph_orchestration:        uses LangGraph StateGraph to orchestrate the workflow; build_graph() returns a CompiledGraph.
- rejects_empty_profile:          returns a plain "Error: ..." string when profile is empty or meaningless.
- rejects_insufficient_profile:   returns an explicit "Error: ..." string when profile lacks minimum required information.
- handles_execution_failure:      if a tool call fails (e.g., API error), the agent catches this and returns a clear error message instead of crashing.
- generates_weekly_plan:          valid input produces a day-by-day plan with exercises, sets, reps, and rest periods.
- handles_constraints:            agent explicitly accounts for physical constraints or injuries using the external tools.
- includes_intensity_progression: output includes RPE-based intensity guidance and a weekly progression strategy.
- includes_nutrition_guidance:    output includes nutritional principles aligned with the stated goal.
- includes_recovery_protocol:     output includes sleep and stretching/recovery recommendations.
- output_schema_enforced:         valid output strictly follows the required sections without conversational filler.
- no_hardcoded_plan:              no hardcoded training plans — all content is LLM-generated based on the input profile.

passed = true only if total_score == 17.
Be strict: partial implementations score 0.
"""


def run_static_eval(
    source_code: str,
    spec_text: str,
    verbose: bool = True,
) -> dict:
    """
    Args:
        source_code: Full Python source code generated by the codegen tool.
        spec_text:   Full spec markdown used to generate the code.
        verbose:     Print results to stdout.

    Returns:
        {"passed": bool, "total_score": int, "max_score": int, "scores": dict, "summary": str}
    """
    prompt = PROMPT_TEMPLATE.format(spec_text=spec_text, source_code=source_code)

    response = llm.invoke(
        [{"role": "user", "content": prompt}]
    )

    import re
    import json

    raw = response.content

    if not raw or raw.strip() == "":
        raise ValueError("LLM returned empty response")

    raw = raw.strip()

    # remove markdown se existir
    raw = re.sub(r"^```json\s*", "", raw)
    raw = re.sub(r"```$", "", raw)

    try:
        result = json.loads(raw)
    except json.JSONDecodeError:
        print("RAW RESPONSE >>>", raw)
        raise

    if verbose:
        print(f"\n=== Static Code Evaluation ===")
        print(f"Score: {result['total_score']}/{result['max_score']} | Passed: {result['passed']}")
        for k, v in result.get("scores", {}).items():
            print(f"  {'✅' if v else '❌'} {k}")
        print(f"\nSummary: {result.get('summary', '')}")

    return result
