"""
static_eval.py - LLM-as-judge static code evaluation.

Evaluates the generated source code against the spec BEFORE execution.

Requires:
    pip install openai
Environment variables:
    OPENAI_API_KEY
"""

import json

from dotenv import load_dotenv
from openai import OpenAI

load_dotenv(override=True)

client = OpenAI()


# ---------------------------------------------------------------------------
# Prompt
# ---------------------------------------------------------------------------

PROMPT_TEMPLATE = """
You are evaluating Python source code generated by a code generation tool.
The code must implement a budget weather routing AI agent using LangGraph, according to the provided specification.

Your task is to evaluate whether the generated code correctly follows the specification BEFORE execution.
Evaluate the criteria below and return ONLY a JSON object - no extra text.

---
SPEC:
{spec_text}

---
GENERATED CODE:
{source_code}

---
Return this exact JSON structure:

{{
  "scores": {{
    "correct_signature":          <0|1>,
    "correct_return_type":        <0|1>,
    "langgraph_orchestration":    <0|1>,
    "llm_usage_for_reasoning":    <0|1>,
    "tools_implemented":          <0|1>,
    "uses_prebuilt_tool_node":    <0|1>,
    "dependent_tool_chain":       <0|1>,
    "output_schema_present":      <0|1>,
    "handles_empty_input":        <0|1>,
    "build_graph_function":       <0|1>
  }},
  "total_score": <int>,
  "max_score": 10,
  "passed": <bool>,
  "summary": "<one paragraph with main issues found, or 'No issues found'>"
}}

Criteria definitions:
- correct_signature:        agent() has exactly (user_request: str) as parameter.
- correct_return_type:      agent() returns a dict (or a tuple where the second element is a dict matching the output schema).
- langgraph_orchestration:  uses LangGraph StateGraph for orchestration, with at least an LLM node and a tools node connected by conditional edges.
- llm_usage_for_reasoning:  ChatOpenAI with model gpt-4o is used and bound to all tools via .bind_tools() to reason about the user request and decide tool calls.
- tools_implemented:        exactly four local tools are defined using @tool from langchain_core.tools: multiply(a, b), add(a, b), select_location(total_budget), and get_weather(location). No MCP servers or external tool protocols.
- uses_prebuilt_tool_node:  ToolNode is imported directly from langgraph.prebuilt and used as the tool execution node. No custom tool node classes, no try/except fallbacks, no monkey-patching.
- dependent_tool_chain:     the implementation requires or strongly instructs the agent to compute multiply first, then pass that result into add, then pass the add result into select_location, then pass the selected location into get_weather. A solution that merely chooses between independent tools scores 0.
- output_schema_present:    output dict contains exactly the keys: status, request_type, total_budget, location, and weather.
- handles_empty_input:      explicitly handles empty or blank user_request and returns status="failure" with request_type=null, total_budget=null, location=null, and weather=null.
- build_graph_function:     code defines a build_graph() function that builds and returns a compiled LangGraph graph.

passed = true only if total_score == max_score.
Be strict: partial implementations score 0.
"""


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def run_static_eval(
    source_code: str,
    spec_text: str,
    verbose: bool = True,
) -> dict:
    """
    Args:
        source_code: Full Python source code generated by the codegen tool.
        spec_text:   Full spec markdown used to generate the code.
        verbose:     Print results to stdout.

    Returns:
        {"passed": bool, "total_score": int, "max_score": int, "scores": dict, "summary": str}
    """
    prompt = PROMPT_TEMPLATE.format(spec_text=spec_text, source_code=source_code)

    response = client.chat.completions.create(
        model="gpt-4o",
        temperature=0,
        messages=[{"role": "user", "content": prompt}],
        response_format={"type": "json_object"},
    )

    result = json.loads(response.choices[0].message.content)

    if verbose:
        print("\n=== Static Code Evaluation ===")
        print(f"Score: {result['total_score']}/{result['max_score']} | Passed: {result['passed']}")
        for key, value in result.get("scores", {}).items():
            mark = "OK" if value else "FAIL"
            print(f"  {mark} {key}")
        print(f"\nSummary: {result.get('summary', '')}")

    return result